CREATE TABLE ORASSADM.POLICES_AUTO (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NUMERO_POLICE VARCHAR2(50) UNIQUE NOT NULL,
    CLIENT_ID NUMBER NOT NULL REFERENCES ORASSADM.CLIENTS(ID) ON DELETE CASCADE,
    VEHICULE VARCHAR2(150),
    IMMATRICULATION VARCHAR2(20),
    FORMULE VARCHAR2(100),
    DATE_ECHEANCE DATE,
    PRIME_ANNUELLE NUMBER DEFAULT 0,
    STATUT VARCHAR2(50) DEFAULT 'Active'
);

